import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const FIXTURES_DIR = fileURLToPath(new URL('../fixtures/', import.meta.url))

export type Phase = 1 | 2 | 3 | 4 | 6 | 10

export interface FixtureMeta {
  /** TS API that produced the content. */
  api: string
  /** Rust phase whose tests consume the fixture. */
  phase: Phase
  /** What the fixture pins. */
  note: string
  /** Set when the content is transcribed from a TS type rather than produced by TS code. */
  validityOnly?: boolean
}

interface IndexEntry extends FixtureMeta {
  path: string
  form: 'pretty' | 'compact'
}

const entries: IndexEntry[] = []

export function resetFixturesDir(): void {
  rmSync(FIXTURES_DIR, { recursive: true, force: true })
  mkdirSync(FIXTURES_DIR, { recursive: true })
}

function writeRaw(path: string, content: string | Uint8Array): void {
  const full = join(FIXTURES_DIR, path)
  mkdirSync(dirname(full), { recursive: true })
  writeFileSync(full, content)
}

/** Writes `JSON.stringify(value, null, 2)` plus a trailing newline. */
export function pretty(path: string, value: unknown, meta: FixtureMeta): void {
  writeRaw(path, JSON.stringify(value, null, 2) + '\n')
  entries.push({ ...meta, path, form: 'pretty' })
}

/** Writes bytes exactly as TS handed them to storage (compact JSON, no trailing newline). */
export function compact(path: string, bytes: Uint8Array, meta: FixtureMeta): void {
  writeRaw(path, bytes)
  entries.push({ ...meta, path, form: 'compact' })
}

export function writeIndex(): void {
  const lines = [
    '# Fixture index',
    '',
    'Generated by `generate.ts`; do not edit. Form `pretty` is `JSON.stringify(value, null, 2)` plus a newline;',
    'form `compact` is the exact bytes TS wrote to storage. Rows marked "validity only" are transcribed from a TS',
    'type rather than produced by TS code, so they prove JSON shape only.',
    '',
    '| Fixture | Form | TS API | Rust phase | What it pins |',
    '|---|---|---|---|---|',
  ]
  for (const e of [...entries].sort((a, b) => (a.path < b.path ? -1 : 1))) {
    const note = e.validityOnly ? `${e.note} (validity only)` : e.note
    lines.push(`| \`${e.path}\` | ${e.form} | ${e.api} | ${e.phase} | ${note} |`)
  }
  lines.push('', `${entries.length} fixtures.`, '')
  writeRaw('INDEX.md', lines.join('\n'))
}
