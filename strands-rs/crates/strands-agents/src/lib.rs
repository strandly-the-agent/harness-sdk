//! Strands Agents SDK for Rust.
//!
//! A model-driven framework for building AI agents: a [`models::Model`], a system prompt,
//! and a list of [`tools::Tool`]s composed into an agent loop.

pub mod agent;
pub mod conversation_manager;
pub mod error;
pub mod hooks;
pub mod logging;
pub mod models;
pub mod plugins;
pub mod retry;
pub mod session;
pub mod state_store;
#[cfg(any(test, feature = "test-support"))]
pub mod test_support;
pub mod tools;
pub mod types;

pub use agent::{
    Agent, AgentBuilder, AgentResult, AgentStream, AgentStreamEvent, InvocationState, InvokeInput,
    InvokeOptions, Limits,
};
pub use agent::{CallOptions, ToolHandle};
pub use conversation_manager::{
    ConversationManager, NullConversationManager, ProactiveCompression, ReduceOptions, ReduceTrigger,
    SlidingWindowConfig, SlidingWindowConversationManager,
};
pub use error::{Error, Result};
pub use models::Model;
pub use plugins::{ModelPlugin, Plugin, PluginRegistry};
pub use session::{FileStorage, SessionManager, Snapshot, SnapshotStorage};
pub use tools::{
    ConcurrentToolExecutor, FunctionTool, SequentialToolExecutor, Tool, ToolContext, ToolExecutor,
};
pub use types::{ContentBlock, Message, Role, StopReason, SystemPrompt};

/// Turns a function into a [`tools::Tool`] implementation (requires the `macros` feature).
#[cfg(feature = "macros")]
pub use strands_agents_macros::tool;

/// Re-exports used by code generated by `#[tool]`; not a stable API.
#[doc(hidden)]
pub mod __private {
    pub use async_trait::async_trait;
    pub use schemars;
    pub use serde;
    pub use serde_json;
}

/// The types most agents need: `use strands_agents::prelude::*;`.
pub mod prelude {
    pub use crate::agent::{Agent, AgentBuilder, AgentResult, InvokeOptions};
    pub use crate::error::{Error, Result};
    pub use crate::models::Model;
    pub use crate::tools::{FunctionTool, Tool, ToolContext};
    pub use crate::types::{ContentBlock, Message, Role, StopReason, SystemPrompt};
    #[cfg(feature = "macros")]
    pub use strands_agents_macros::tool;
}
